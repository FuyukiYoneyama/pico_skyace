// ムソルグスキー 組曲「展覧会の絵」より 第10曲「キーウの大門」(冒頭～中間部)。
// 実行時に MIDI を解釈するのではなく、ビルド前に音符列へ変換して同梱する方式
// （アセット変換はビルド前処理、実行時パースはしない方針）。
//
// 原曲は Modest Mussorgsky 作曲「展覧会の絵」（作曲者は1881年没、原曲自体は
// パブリックドメイン）。ただし今回使用した MIDI 演奏データ自体は
// 「音楽の素材館 by MIDI Classics」(Windy softmedia service, windy-vis.com)
// の著作物であり、パブリックドメインではない:
//   https://windy-vis.com/cgi/fnavi/clsnavi.cgi?links=652
//   https://windy-vis.com/art/download/index.html
// 同サイトの利用規約により、個人・非商業目的（ゲームでの利用を含む）は
// クレジット表記を条件に無償利用可、大規模な商業利用は別途有料ライセンスが
// 必要、ファイルそのものの再配布は禁止。本リポジトリは MIDI ファイル自体は
// 同梱せず、そこから機械的に抽出した音符列（周波数/長さのみ）だけを含む。
// note: 元ファイルは第9曲「バーバ・ヤガーの小屋」(高速・不協和)と第10曲
// 「キーウの大門」(荘厳・低速)が連結された約9分のファイル。全体の先頭(0秒)
// から単純に91秒切り出すと第9曲の高速パッセージしか収録されず、誰もが
// イメージする「大門」の旋律にならない。曲中のノート密度（音数/秒）を
// 分析し、疎密の変化から「キーウの大門」の主題が入るタイミング（約344秒
// 付近）を特定し、そこから110秒を収録している。

// 元データの全パート/トラックを1つの音符プールにマージし、同時に鳴っている
// 音から4声を機械的に抽出した（ソプラノ/アルト/テノール/バスの4部合唱に
// 見立てた skyline 抽出）: 最高音=kMelodyNotes、2番目に高い音=kAltoNotes、
// 2番目に低い音=kTenorNotes、最低音=kBassNotes（alto/tenor は held note が
// 1つしか無い瞬間はそれぞれ最高音/最低音にフォールバック）。同時発音数を
// 2→3→4 と増やすための構成。
// 抽出直後は、和音内の各音の note-off がわずかにずれることで生じる短い
// ディップ/スパイク（例: 同じ音が続く間に一瞬だけ別の音が挟まる）が
// 大量に混ざり旋律が細かく揺れていたため、「短時間だけ元の音より低く
// （ソプラノ・アルト側）/高く（テノール・バス側）なった直後に元の音へ戻る」
// 区間を前の音に吸収するスムージングを行っている。
// テンポマップ（強弱表現込みの演奏データのため揺れが大きい）で実時間(ms)に
// 変換済み。freq_hz=0 は休符。
